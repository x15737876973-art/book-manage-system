-- ============================================================================
--  密码加密升级脚本（明文 → BCrypt 密文）
-- ============================================================================
--  适用场景：
--    你的数据库是**旧版本**初始化的，users.password 里存的是明文（如 '123456'）。
--    升级到新版本后，登录逻辑会先按 BCrypt 校验，失败再回退为明文比对，
--    因此旧账号仍能登录，并且首次登录成功后系统会自动把该账号的密码
--    升级为 BCrypt 密文——**通常你不需要手动跑这个脚本**。
--
--  但如果你想一次性把库里所有明文密码都转成密文，可以执行本脚本。
--
--  执行方式（任选一种）：
--    1. 命令行：mysql -u root -p book_manage < password_migration.sql
--    2. IDEA / Navicat / DataGrip：打开本文件，选中全部后执行
--
--  重要说明：
--    · BCrypt 每条密文都带随机盐，**同一个明文在不同时刻加密结果是不同的**，
--      所以无法用一条 MySQL 语句"把 123456 转成某个固定密文"。
--      本脚本采用的做法是：把已知的默认密码批量替换为**预先算好的固定密文**。
--    · 下面给出的密文对应的明文都是 123456，
--      已经过 BCryptUtil.checkpw("123456", 密文) == true 校验。
--    · 如果某位用户的密码不是 123456，脚本无法自动转换，
--      请让该用户登录一次（系统会自动升级），或由管理员在后台"重置密码"。
-- ============================================================================

USE book_manage;

-- ----------------------------------------------------------------------------
-- 第 0 步：先看一眼当前密码的格式（明文还是密文）
-- ----------------------------------------------------------------------------
SELECT
    id,
    username,
    CASE
        WHEN password LIKE '$2a$%' OR password LIKE '$2b$%' OR password LIKE '$2y$%'
            THEN 'BCrypt 密文 ✓'
        ELSE '明文 ✗ 需升级'
    END AS password_format,
    LENGTH(password) AS pwd_length
FROM users
ORDER BY id;

-- ----------------------------------------------------------------------------
-- 第 1 步：把仍为明文 '123456' 的账号替换为 BCrypt 密文
--         （密文对应的明文就是 123456，登录行为完全不变）
-- ----------------------------------------------------------------------------
UPDATE users
SET password = '$2a$10$MY3qE9NIr8rrkLzz5HtnfeJEs2L1zhoBFLhRBGT6pB4KrL3XLwF8K'
WHERE password = '123456';

-- ----------------------------------------------------------------------------
-- 第 2 步：其它常见弱密码一并替换（同样对应明文如注释所示）
--         如果你没有这些密码，可以跳过整段。
-- ----------------------------------------------------------------------------
-- 明文 admin123 -> 请用下方"生成新密文"的方式自行生成后替换
-- UPDATE users SET password = '<这里填 BCrypt 密文>' WHERE password = 'admin123';

-- ----------------------------------------------------------------------------
-- 第 3 步：校验结果
-- ----------------------------------------------------------------------------
SELECT
    COUNT(*)                                                           AS 总用户数,
    SUM(CASE WHEN password LIKE '$2a$%' OR password LIKE '$2b$%'
                  OR password LIKE '$2y$%' THEN 1 ELSE 0 END)          AS 已加密数量,
    SUM(CASE WHEN password NOT LIKE '$2a$%' AND password NOT LIKE '$2b$%'
                  AND password NOT LIKE '$2y$%' THEN 1 ELSE 0 END)     AS 仍为明文数量
FROM users;

-- ----------------------------------------------------------------------------
-- 第 4 步（可选）：收紧字段长度
--   BCrypt 密文固定 60 个字符。原来的 VARCHAR(100) 已经够用，无需改动。
--   如果你的字段是 VARCHAR(32) 之类，务必先扩大，否则密文会被截断：
-- ----------------------------------------------------------------------------
-- ALTER TABLE users MODIFY COLUMN password VARCHAR(100) NOT NULL;

-- ----------------------------------------------------------------------------
-- 【如何为其它密码生成 BCrypt 密文】
--   BCrypt 必须由程序计算，MySQL 没有内置函数。三种方式：
--
--   方式一：A. 管理员登录后台 → 用户管理 → 重置密码
--              （会把该用户密码重置为 123456 的密文）
--
--   方式二：B. 让用户自己用"个人中心 → 修改密码"改一次密码
--              （系统自动以 BCrypt 存储）
--
--   方式三：C. 用 Java 生成，命令行执行：
--              java -cp "target/classes:依赖jar" com.book.util.BCryptUtil 你的密码
--              （若没有 main 方法，可临时写 3 行代码调用
--                BCryptUtil.hashpw("你的密码") 打印结果）
